// Run from the repository root: fvm dart run scripts/generate_localization_test.dart
// Keeps runtime lookup coverage in step with the source ARB catalog
import 'dart:convert';
import 'dart:io';

void main() {
  final root = Directory.current.absolute;
  final source = File('${root.path}/lib/l10n/app_en.arb');
  final catalog = jsonDecode(source.readAsStringSync()) as Map<String, dynamic>;
  final output = File('${root.path}/test/generated/localization_messages.dart');
  final text = StringBuffer('''// Generated by scripts/generate_localization_test.dart; do not edit
import 'package:templates/l10n/localizations.dart';

Map<String, String> readMessages(AppLocalizations l10n) => {
''');
  for (final key in catalog.keys.where((key) => !key.startsWith('@'))) {
    final metadata = catalog['@$key'] as Map<String, dynamic>?;
    final placeholders = metadata?['placeholders'] as Map<String, dynamic>?;
    final arguments = placeholders?.values.map((dynamic value) {
      final type = (value as Map<String, dynamic>)['type'];

      return switch (type) {
        'int' => '2',
        'double' || 'num' => '4.5',
        _ => "'sample'",
      };
    });
    final call = arguments == null ? '' : '(${arguments.join(', ')})';
    text.writeln("  '$key': l10n.$key$call,");
  }
  text.writeln('};');
  output.parent.createSync(recursive: true);
  output.writeAsStringSync(text.toString());
  final format = Process.runSync(Platform.resolvedExecutable, ['format', output.path]);
  stdout.write(format.stdout);
  stderr.write(format.stderr);
  exitCode = format.exitCode;
}
