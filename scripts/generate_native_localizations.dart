// Run from the repository root: fvm dart run scripts/generate_native_localizations.dart
// Compiles ARB translations into native menus and platform language declarations
import 'dart:convert';
import 'dart:io';

import 'package:templates/app/app_identity.dart';

void main(List<String> arguments) {
  final isCheck = arguments.length == 1 && arguments.single == '--check';
  if (arguments.isNotEmpty && !isCheck) {
    throw ArgumentError('Usage: dart run scripts/generate_native_localizations.dart [--check]');
  }
  final root = Directory.current.resolveSymbolicLinksSync();
  final git = Process.runSync('git', ['rev-parse', '--show-toplevel']);
  final hasGitRoot = git.exitCode == 0;
  if (!hasGitRoot) {
    throw StateError('Run this tool from the repository root');
  }
  final isRepositoryRoot = Directory((git.stdout as String).trim()).resolveSymbolicLinksSync() == root;
  if (!isRepositoryRoot) {
    throw StateError('Run this tool from the repository root');
  }

  final source = _readCatalog('$root/lib/l10n/app_en.arb');
  final sourceKeys = source.keys.where((key) => !key.startsWith('@')).toSet();
  final nib = File('$root/macos/Runner/Base.lproj/MainMenu.xib').readAsStringSync();
  final titles = <String, String>{};
  for (final tag in RegExp(r'<[^>]+\btitle="([^"]*)"[^>]*>').allMatches(nib)) {
    final id = RegExp(r'\bid="([^"]+)"').firstMatch(tag.group(0)!)?.group(1);
    if (id != null) {
      titles[id] = tag.group(1)!;
    }
  }
  final hasMatchingIds =
      titles.keys.toSet().containsAll(nativeMenuKeys.keys) && nativeMenuKeys.keys.toSet().containsAll(titles.keys);
  if (!hasMatchingIds) {
    throw StateError('The native menu mapping must cover every title in MainMenu.xib');
  }
  for (final entry in nativeMenuKeys.entries) {
    final expected = entry.value == null
        ? 'APP_NAME'
        : (source[entry.value] as String).replaceAll('{appName}', 'APP_NAME');
    if (titles[entry.key] != expected) {
      throw StateError('The source menu title changed: ${entry.key}');
    }
  }

  final runner = Directory('$root/macos/Runner').resolveSymbolicLinksSync();
  final isRunnerInsideRepository = runner.startsWith('$root/');
  if (!isRunnerInsideRepository) {
    throw StateError('The native resource destination must be inside the repository');
  }
  final outputs = <String, String>{};
  final locales = <String>[];
  final files = Directory('$root/lib/l10n').listSync().whereType<File>().toList()
    ..sort((a, b) => a.path.compareTo(b.path));
  for (final file in files) {
    final match = RegExp(
      r'^app_([a-z]{2}(?:_[A-Z][a-z]{3})?(?:_(?:[A-Z]{2}|[0-9]{3}))?)\.arb$',
    ).firstMatch(file.uri.pathSegments.last);
    if (match == null) {
      continue;
    }
    final locale = match.group(1)!;
    locales.add(locale.replaceAll('_', '-'));
    final catalog = _readCatalog(file.path);
    final keys = catalog.keys.where((key) => !key.startsWith('@')).toSet();
    final hasCompleteCatalog = keys.containsAll(sourceKeys) && sourceKeys.containsAll(keys);
    if (!hasCompleteCatalog) {
      throw StateError('The $locale catalog must translate every source message');
    }
    final text = StringBuffer('// Generated by scripts/generate_native_localizations.dart; do not edit\n');
    for (final entry in nativeMenuKeys.entries) {
      final value = entry.value == null ? AppIdentity.name : catalog[entry.value];
      final hasMessage = value is String && value.trim().isNotEmpty;
      if (!hasMessage) {
        throw StateError('Missing native message ${entry.value} in $locale');
      }
      final title = value.replaceAll('{appName}', AppIdentity.name);
      text.writeln('${jsonEncode('${entry.key}.title')} = ${jsonEncode(title)};');
    }
    final directory = Directory('$runner/${locale.replaceAll('_', '-')}.lproj');
    final hasEscapingDirectory = directory.existsSync() && !directory.resolveSymbolicLinksSync().startsWith('$root/');
    if (hasEscapingDirectory) {
      throw StateError('The localized resource destination must be inside the repository');
    }
    outputs['${directory.path}/MainMenu.strings'] = text.toString();
  }
  outputs.addAll(_platformLanguages(root, locales));
  if (isCheck) {
    final stale = outputs.entries
        .where((entry) {
          final file = File(entry.key);
          return !file.existsSync() || file.readAsStringSync() != entry.value;
        })
        .map((entry) => entry.key.substring(root.length + 1))
        .toList();
    if (stale.isNotEmpty) {
      throw StateError('Regenerate native localizations: ${stale.join(', ')}');
    }
    stdout.writeln('Verified ${locales.length} locales across ${outputs.length} native resources');
    return;
  }
  for (final entry in outputs.entries) {
    final output = File(entry.key);
    output.parent.createSync(recursive: true);
    if (!output.parent.resolveSymbolicLinksSync().startsWith('$root/')) {
      throw StateError('The native resource destination must be inside the repository');
    }
    final temporary = File('${output.path}.tmp')..writeAsStringSync(entry.value);
    temporary.renameSync(output.path);
  }
  stdout.writeln('Generated ${locales.length} locales across ${outputs.length} native resources');
}

Map<String, String> _platformLanguages(String root, List<String> locales) {
  final outputs = <String, String>{};
  for (final platform in ['ios', 'macos']) {
    final plist = '$root/$platform/Runner/Info.plist';
    final source = File(plist).readAsStringSync();
    final list = RegExp(r'(<key>CFBundleLocalizations</key>\n\t<array>\n)[\s\S]*?(\t</array>)');
    if (list.allMatches(source).length != 1) {
      throw StateError('Expected one language declaration in $platform Info.plist');
    }
    outputs[plist] = source.replaceFirstMapped(
      list,
      (match) => '${match[1]}${locales.map((locale) => '\t\t<string>$locale</string>\n').join()}${match[2]}',
    );

    final project = '$root/$platform/Runner.xcodeproj/project.pbxproj';
    final projectSource = File(project).readAsStringSync();
    final regions = RegExp(r'\t\t\tknownRegions = \([\s\S]*?\t\t\t\);');
    if (regions.allMatches(projectSource).length != 1) {
      throw StateError('Expected one knownRegions list in $platform');
    }
    var candidate = projectSource.replaceFirst(
      regions,
      '\t\t\tknownRegions = (\n\t\t\t\tBase,\n'
      '${locales.map((locale) => '\t\t\t\t${jsonEncode(locale)},\n').join()}\t\t\t);',
    );
    if (platform == 'macos') {
      String id(String locale) =>
          '10CA${locale.codeUnits.map((unit) => unit.toRadixString(16).padLeft(2, '0')).join().toUpperCase().padRight(20, '0')}';
      final references = RegExp(r'\t\t10CA[0-9A-F]{20} /\* [^*]+ \*/ = \{isa = PBXFileReference;[^\n]*\n');
      if (references.allMatches(candidate).isEmpty) {
        throw StateError('Expected localized native menu references');
      }
      candidate = candidate.replaceAll(references, '');
      const endReferences = '/* End PBXFileReference section */';
      if (endReferences.allMatches(candidate).length != 1) {
        throw StateError('Expected one PBXFileReference section');
      }
      candidate = candidate.replaceFirst(
        endReferences,
        '${locales.map((locale) => '\t\t${id(locale)} /* $locale */ = {isa = PBXFileReference; lastKnownFileType = text.plist.strings; name = ${jsonEncode(locale)}; path = ${jsonEncode('$locale.lproj/MainMenu.strings')}; sourceTree = "<group>"; };\n').join()}$endReferences',
      );
      final menu = RegExp(
        r'(33CC10F42044A3C60003C045 /\* MainMenu.xib \*/ = \{\n\t\t\tisa = PBXVariantGroup;\n\t\t\tchildren = \(\n)[\s\S]*?(\t\t\t\);)',
      );
      if (menu.allMatches(candidate).length != 1) {
        throw StateError('Expected one native MainMenu variant group');
      }
      candidate = candidate.replaceFirstMapped(
        menu,
        (match) =>
            '${match[1]}\t\t\t\t33CC10F52044A3C60003C045 /* Base */,\n'
            '${locales.map((locale) => '\t\t\t\t${id(locale)} /* $locale */,\n').join()}${match[2]}',
      );
    }
    outputs[project] = candidate;
  }
  outputs['$root/android/app/src/main/res/xml/locale_config.xml'] =
      '<?xml version="1.0" encoding="utf-8"?>\n'
      '<!-- Generated by scripts/generate_native_localizations.dart; do not edit. -->\n'
      '<locale-config xmlns:android="http://schemas.android.com/apk/res/android">\n'
      '${locales.map((locale) => '    <locale android:name="$locale" />\n').join()}'
      '</locale-config>\n';
  return outputs;
}

Map<String, dynamic> _readCatalog(String path) => jsonDecode(File(path).readAsStringSync()) as Map<String, dynamic>;

